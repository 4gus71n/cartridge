#!/usr/bin/env python3
"""Generate web/mapdata.js: room labels for the in-game minimap.

Reads the vendored Open Adventure dungeon (vendor/open-adventure/adventure.yaml)
and writes, for every location index (the same ids the engine stores in its save
file), a short label for the map. Preference order: the dungeon's own `maptag`,
then a tidied `short` description, then the LOC_ symbol.

Run after updating the vendored engine:
    python3 tools/build_mapdata.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
YAML = ROOT / "vendor" / "open-adventure" / "adventure.yaml"
OUT = ROOT / "web" / "mapdata.js"

# "You're in ..." / "You are in ..." / "You're at ..." -> the place itself.
LEAD = re.compile(
    r"^(?:you(?:'re| are)\s+)?"
    r"(?:in|at|on|inside|outside|above|below|beside|before|near|atop|north of|south of|east of|west of)\s+",
    re.I,
)


def tidy(text: str) -> str:
    label = text.strip().strip("'\"").rstrip(".")
    label = label.replace("''", "'")  # YAML single-quoted escaping
    label = LEAD.sub("", label)
    label = re.sub(r"^(?:the|a|an)\s+", "", label, flags=re.I)
    label = re.sub(r"\s+", " ", label).strip()
    return (label[:1].upper() + label[1:]) if label else ""


def main() -> None:
    text = YAML.read_text()
    body = text[text.index("locations:"):]
    # Split on top-level "- LOC_NAME:" entries.
    chunks = re.split(r"^- (LOC_\w+):$", body, flags=re.M)[1:]
    labels = []
    for i in range(0, len(chunks), 2):
        name, block = chunks[i], chunks[i + 1]
        maptag = re.search(r"^\s*maptag:\s*(.+)$", block, re.M)
        short = re.search(r"^\s*short:\s*(.+)$", block, re.M)
        label = ""
        if maptag and "null" not in maptag.group(1):
            label = tidy(maptag.group(1))
        if not label and short and "null" not in short.group(1):
            label = tidy(short.group(1))
        if not label:
            label = tidy(name.removeprefix("LOC_").replace("_", " ").title())
        labels.append(label)
    OUT.write_text(
        "/* Generated by tools/build_mapdata.py - do not edit. */\n"
        "(function (root) {\n"
        '  "use strict";\n'
        "  var ROOM_LABELS = " + json.dumps(labels, indent=0).replace("\n", "") + ";\n"
        '  if (typeof module !== "undefined" && module.exports) module.exports = ROOM_LABELS;\n'
        "  else root.ROOM_LABELS = ROOM_LABELS;\n"
        "})(typeof self !== \"undefined\" ? self : this);\n"
    )
    print(f"wrote {OUT} ({len(labels)} rooms)")


if __name__ == "__main__":
    main()
